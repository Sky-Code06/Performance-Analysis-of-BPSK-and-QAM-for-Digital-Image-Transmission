function fig = plot_ber_snr(snr_range, sim_ber_bpsk, theo_ber_bpsk, sim_ber_qam, theo_ber_qam)
% PLOT_BER_SNR Plots comparative Bit Error Rate (BER) vs. SNR curves.
%
% Syntax:
%   fig = plot_ber_snr(snr_range, sim_ber_bpsk, theo_ber_bpsk, sim_ber_qam, theo_ber_qam)
%
% Features:
%   - BPSK Simulated (markers) vs Theoretical (solid line)
%   - 16-QAM Simulated (markers) vs Theoretical (dashed line)
%   - Logarithmic Y-axis (semilogy) down to 1e-6
%   - Highlights the ~4 dB SNR trade-off for 4x spectral efficiency
%
% DCS Project: Performance Analysis of BPSK and QAM for Digital Image Transmission
% Authors: Glenn Monteiro (24BEC0474), Sanskriti Sarkar (24BEC0183), Aakash Nair (24BEC0080)
% VIT - School of Electronics Engineering (SENSE)

    fig = figure('Name', 'BER vs SNR Performance Analysis', ...
                 'Color', 'w', 'Position', [150, 150, 850, 600]);
    hold on; box on; grid on;
    set(gca, 'YScale', 'log', 'YMinorGrid', 'on', 'FontSize', 11);

    % Theoretical curves (fine resolution if possible or matched)
    p1 = semilogy(snr_range, theo_ber_bpsk, 'b-', 'LineWidth', 2.0, ...
                  'DisplayName', 'BPSK Theoretical: Q(\surd(2E_b/N_0))');
    p2 = semilogy(snr_range, theo_ber_qam, 'r--', 'LineWidth', 2.0, ...
                  'DisplayName', '16-QAM Theoretical (Gray Coded)');

    % Simulated curves
    p3 = semilogy(snr_range, sim_ber_bpsk, 'bo', 'MarkerSize', 7, ...
                  'MarkerFaceColor', [0.2 0.5 0.9], 'LineWidth', 1.2, ...
                  'DisplayName', 'BPSK Simulated (Image Bitstream)');
    p4 = semilogy(snr_range, sim_ber_qam, 'rs', 'MarkerSize', 7, ...
                  'MarkerFaceColor', [0.9 0.3 0.2], 'LineWidth', 1.2, ...
                  'DisplayName', '16-QAM Simulated (Image Bitstream)');

    % Clamp Y-axis minimum to 1e-6 for clean display
    ylim([1e-6, 0.5]);
    xlim([min(snr_range), max(snr_range)]);

    xlabel('E_b / N_0 (dB)', 'FontSize', 12, 'FontWeight', 'bold');
    ylabel('Bit Error Rate (BER)', 'FontSize', 12, 'FontWeight', 'bold');
    title('Bit Error Rate (BER) vs. E_b/N_0 Performance in AWGN Channel', ...
          'FontSize', 13, 'FontWeight', 'bold');

    legend([p1, p3, p2, p4], 'Location', 'southwest', 'FontSize', 10);

    % Annotate Key Trade-off Insight
    annotation('textbox', [0.55, 0.65, 0.33, 0.20], ...
               'String', { ...
                   '\bf{Trade-off Analysis:}', ...
                   '\bullet \bf{BPSK:} Maximum noise immunity', ...
                   '  (Requires ~4 dB lower SNR for 10^{-3} BER)', ...
                   '  \eta = 1 bit/s/Hz', ...
                   '\bullet \bf{16-QAM:} 4\times Spectral Efficiency', ...
                   '  \eta = 4 bit/s/Hz', ...
                   '  Susceptible to tighter constellation packing' ...
               }, ...
               'FitBoxToText', 'on', 'BackgroundColor', [0.97 0.97 0.97], ...
               'EdgeColor', [0.7 0.7 0.7], 'FontSize', 9);
end
